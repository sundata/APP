    // MARK: - 星座ごとのテーマ割り当て

    /// 星座ごとに 20 件のテーマを割り当てる。
    /// 共通プール（30 件）から星座ごとに異なる開始位置とステップで選ぶため、
    /// 同じ日でも星座によって主題が変わり、各星座は 20 件の主題を持つ。
    public static func themeIndices(for zodiac: Zodiac) -> [Int] {
        let poolSize = themes.count
        var indices: [Int] = []
        var used = Set<Int>()
        var step = 0
        while indices.count < themesPerZodiac {
            let candidate = (zodiac.ordinal * 11 + step * 7) % poolSize
            if !used.contains(candidate) {
                used.insert(candidate)
                indices.append(candidate)
            }
            step += 1
            if step > poolSize * 4 { break }
        }
        return indices
    }

    /// 1 星座あたりのテーマ数（要件: 20 件以上）。
    public static let themesPerZodiac = 20

    static func theme(for zodiac: Zodiac, rotation: Int) -> Theme {
        let indices = themeIndices(for: zodiac)
        return themes[indices.cyclicElement(at: rotation)]
    }
